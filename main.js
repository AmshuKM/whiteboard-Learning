// Electron main process: window, settings, session storage, and AI provider calls.
// AI calls run here (not in the renderer) so the Claude API key never touches the
// web page and Ollama requests aren't subject to browser CORS rules.
const { app, BrowserWindow, ipcMain, safeStorage, shell } = require('electron');
const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const Anthropic = require('@anthropic-ai/sdk').default;

const SYSTEM_PROMPT = `You are a learning companion built into a whiteboard app. The screen has a whiteboard and a chat panel.

With each user message you may receive an image: a snapshot of the user's whiteboard at the moment they pressed send. If the whiteboard is empty, no image is attached and the message says so.

How to behave:
- The user will often ask you to take on a role, such as an interviewer, tutor, or examiner on a topic. Stay in that role until they change it.
- When you ask a question that is best answered visually (diagrams, circuits, cross-sections, graphs, derivations, flowcharts), say clearly that they should draw it on the whiteboard.
- Ask one question at a time. Start at the level the user asks for, and adapt the difficulty to how they are doing.
- When the user submits an answer, evaluate the whiteboard drawing together with any text they typed:
  - Briefly say what you see on the board, so the user knows you read it correctly.
  - If something is wrong or missing, say exactly what. Give the correct version (labels, structure, reasoning) and explain why. Then either ask them to fix it or move on, whichever helps learning more.
  - If it is correct, confirm it briefly, add one useful insight if there is one, and then ask a follow-up or the next question.
- Hand-drawn diagrams are rough. Judge the concept, not the drawing quality. If something is truly unreadable, ask about that specific part instead of guessing.
- If the board has nothing to do with the current message, ignore it.
- Keep replies short enough to read in a small chat window. Use Markdown, and use short lists where they help.`;

// ---------- storage ----------
// Tests point this at a temp folder so they never touch real sessions/settings.
if (process.env.WHITEBOARD_TUTOR_DATA_DIR) app.setPath('userData', process.env.WHITEBOARD_TUTOR_DATA_DIR);

const userDir = () => app.getPath('userData');
const settingsPath = () => path.join(userDir(), 'settings.json');
const sessionsDir = () => {
  const d = path.join(userDir(), 'sessions');
  fs.mkdirSync(d, { recursive: true });
  return d;
};

const DEFAULT_SETTINGS = {
  provider: 'ollama',
  ollamaUrl: 'http://localhost:11434',
  ollamaModel: '',
  claudeModel: 'claude-opus-5-5',
  claudeEffort: 'medium',
  claudeKeyEnc: null, // API key encrypted with the OS keychain via safeStorage
};

function readSettings() {
  try {
    return { ...DEFAULT_SETTINGS, ...JSON.parse(fs.readFileSync(settingsPath(), 'utf8')) };
  } catch {
    return { ...DEFAULT_SETTINGS };
  }
}

function writeSettings(s) {
  fs.writeFileSync(settingsPath(), JSON.stringify(s, null, 2));
}

function getClaudeKey(s) {
  if (s.claudeKeyEnc) {
    try {
      const buf = Buffer.from(s.claudeKeyEnc, 'base64');
      return safeStorage.isEncryptionAvailable() ? safeStorage.decryptString(buf) : buf.toString('utf8');
    } catch {
      return null;
    }
  }
  return process.env.ANTHROPIC_API_KEY || null;
}

// Path-safe session id check (ids are generated by us, but never trust IPC input).
const validId = (id) => typeof id === 'string' && /^[a-zA-Z0-9-]{1,64}$/.test(id);

// ---------- IPC: settings ----------
ipcMain.handle('settings:get', () => {
  const s = readSettings();
  const { claudeKeyEnc, ...rest } = s;
  return { ...rest, hasClaudeKey: !!getClaudeKey(s), keyFromEnv: !claudeKeyEnc && !!process.env.ANTHROPIC_API_KEY };
});

ipcMain.handle('settings:set', (_e, patch) => {
  const s = readSettings();
  const allowed = ['provider', 'ollamaUrl', 'ollamaModel', 'claudeModel', 'claudeEffort'];
  for (const k of allowed) if (k in patch) s[k] = patch[k];
  if (typeof patch.claudeKey === 'string') {
    const key = patch.claudeKey.trim();
    if (!key) s.claudeKeyEnc = null;
    else if (safeStorage.isEncryptionAvailable()) s.claudeKeyEnc = safeStorage.encryptString(key).toString('base64');
    else s.claudeKeyEnc = Buffer.from(key, 'utf8').toString('base64');
  }
  writeSettings(s);
  return true;
});

ipcMain.handle('ollama:models', async (_e, url) => {
  const base = (url || readSettings().ollamaUrl).replace(/\/+$/, '');
  const res = await fetch(`${base}/api/tags`);
  if (!res.ok) throw new Error(`Ollama returned ${res.status}`);
  const data = await res.json();
  return (data.models || []).map((m) => m.name);
});

// ---------- IPC: sessions ----------
ipcMain.handle('sessions:list', () => {
  const dir = sessionsDir();
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => {
      try {
        const s = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
        return { id: s.id, title: s.title, updatedAt: s.updatedAt };
      } catch {
        return null;
      }
    })
    .filter(Boolean)
    .sort((a, b) => b.updatedAt - a.updatedAt);
});

ipcMain.handle('sessions:load', (_e, id) => {
  if (!validId(id)) throw new Error('bad id');
  return JSON.parse(fs.readFileSync(path.join(sessionsDir(), `${id}.json`), 'utf8'));
});

ipcMain.handle('sessions:save', (_e, session) => {
  if (!validId(session?.id)) throw new Error('bad id');
  session.updatedAt = Date.now();
  fs.writeFileSync(path.join(sessionsDir(), `${session.id}.json`), JSON.stringify(session));
  return true;
});

ipcMain.handle('sessions:delete', (_e, id) => {
  if (!validId(id)) throw new Error('bad id');
  fs.rmSync(path.join(sessionsDir(), `${id}.json`), { force: true });
  return true;
});

ipcMain.handle('sessions:newId', () => crypto.randomUUID());

// ---------- IPC: chat ----------
// The renderer sends: { requestId, messages: [{ role, text, image? }] }
// where image is a base64 PNG (no data: prefix), present only on the latest user turn.
// Text chunks stream back on 'chat:chunk'; the handler resolves with the full reply.
const controllers = new Map();

ipcMain.handle('chat:send', async (event, { requestId, messages }) => {
  const s = readSettings();
  const ac = new AbortController();
  controllers.set(requestId, ac);
  const emit = (text) => event.sender.send('chat:chunk', { requestId, text });
  try {
    if (s.provider === 'claude') return await chatClaude(s, messages, emit, ac.signal);
    return await chatOllama(s, messages, emit, ac.signal);
  } finally {
    controllers.delete(requestId);
  }
});

ipcMain.handle('chat:cancel', (_e, requestId) => {
  controllers.get(requestId)?.abort();
  return true;
});

async function chatClaude(s, messages, emit, signal) {
  const apiKey = getClaudeKey(s);
  if (!apiKey) throw new Error('No Claude API key set. Add one in Settings.');
  const client = new Anthropic({ apiKey });

  const apiMessages = messages.map((m) => {
    if (m.role === 'assistant') return { role: 'assistant', content: m.text };
    const content = [];
    if (m.image) content.push({ type: 'image', source: { type: 'base64', media_type: 'image/png', data: m.image } });
    content.push({ type: 'text', text: m.text });
    return { role: 'user', content };
  });

  const stream = client.beta.messages.stream(
    {
      model: s.claudeModel,
      max_tokens: 64000,
      system: SYSTEM_PROMPT,
      thinking: { type: 'adaptive' },
      output_config: { effort: s.claudeEffort || 'medium' },
      // If a safety classifier declines, the server retries on a fallback model.
      betas: ['server-side-fallback-2026-07-01'],
      fallbacks: 'default',
      messages: apiMessages,
    },
    { signal },
  );

  let full = '';
  try {
    for await (const ev of stream) {
      if (ev.type === 'content_block_delta' && ev.delta.type === 'text_delta') {
        full += ev.delta.text;
        emit(ev.delta.text);
      }
    }
    const final = await stream.finalMessage();
    if (final.stop_reason === 'refusal') {
      const note = '\n\n_(The model declined to answer this request.)_';
      full += note;
      emit(note);
    }
  } catch (err) {
    if (err instanceof Anthropic.AuthenticationError) throw new Error('Claude rejected the API key. Check it in Settings.');
    if (err instanceof Anthropic.RateLimitError) throw new Error('Claude rate limit reached. Wait a moment and try again.');
    if (err instanceof Anthropic.APIError) throw new Error(`Claude API error ${err.status ?? ''}: ${err.message}`);
    throw err;
  }
  return full;
}

async function chatOllama(s, messages, emit, signal) {
  if (!s.ollamaModel) throw new Error('No Ollama model selected. Pick one in Settings.');
  const base = s.ollamaUrl.replace(/\/+$/, '');
  const body = {
    model: s.ollamaModel,
    stream: true,
    messages: [
      { role: 'system', content: SYSTEM_PROMPT },
      ...messages.map((m) => (m.image ? { role: m.role, content: m.text, images: [m.image] } : { role: m.role, content: m.text })),
    ],
  };

  let res;
  try {
    res = await fetch(`${base}/api/chat`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
      signal,
    });
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    throw new Error(`Can't reach Ollama at ${base}. Is it running? (ollama serve)`);
  }
  if (!res.ok) {
    const t = await res.text();
    throw new Error(`Ollama error ${res.status}: ${t.slice(0, 300)}`);
  }

  // Ollama streams newline-delimited JSON objects.
  const decoder = new TextDecoder();
  let buf = '';
  let full = '';
  for await (const chunk of res.body) {
    buf += decoder.decode(chunk, { stream: true });
    let nl;
    while ((nl = buf.indexOf('\n')) >= 0) {
      const line = buf.slice(0, nl).trim();
      buf = buf.slice(nl + 1);
      if (!line) continue;
      const obj = JSON.parse(line);
      if (obj.error) throw new Error(`Ollama: ${obj.error}`);
      const piece = obj.message?.content || '';
      if (piece) {
        full += piece;
        emit(piece);
      }
    }
  }
  return full;
}

// ---------- window ----------
function createWindow() {
  const win = new BrowserWindow({
    width: 1400,
    height: 860,
    minWidth: 900,
    minHeight: 560,
    title: 'Whiteboard Tutor',
    backgroundColor: '#f4f4f2',
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });
  win.setMenuBarVisibility(false);
  win.loadFile(path.join(__dirname, 'src', 'index.html'));
  // Open links from chat replies in the system browser, never inside the app.
  win.webContents.setWindowOpenHandler(({ url }) => {
    if (/^https?:/.test(url)) shell.openExternal(url);
    return { action: 'deny' };
  });
  win.webContents.on('will-navigate', (e) => e.preventDefault());
}

app.whenReady().then(() => {
  createWindow();
  app.on('activate', () => BrowserWindow.getAllWindows().length === 0 && createWindow());
});
app.on('window-all-closed', () => process.platform !== 'darwin' && app.quit());
